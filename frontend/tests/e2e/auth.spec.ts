import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'

test('真实注册、登录、资料、改密、多会话撤销与退出',async({page,context,browser,baseURL},testInfo)=>{
 const email=`e2e-${randomUUID()}@example.test`,password=`Initial-${randomUUID()}`,nextPassword=`Updated-${randomUUID()}`
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/settings');await expect(page).toHaveURL(/\/login/)
 await page.getByRole('link',{name:'创建账号'}).click()
 await page.getByLabel('昵称',{exact:true}).fill('协作同学')
 await page.getByLabel('邮箱',{exact:true}).fill(email)
 await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByLabel('确认密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'创建账号',exact:true}).click()
 await expect(page).toHaveURL(/\/login\?registered=1/)
 await page.getByLabel('邮箱',{exact:true}).fill(email)
 await page.getByLabel('密码',{exact:true}).fill('Incorrect-password')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'邮箱或密码错误'})).toBeVisible()
 await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page).toHaveURL(/\/teams$/)
 await expect(page.getByText('你好，协作同学。')).toBeVisible()
 const cookie=(await context.cookies()).find(c=>c.name==='taskflow_session')
 expect(cookie?.httpOnly).toBe(true);expect(cookie?.sameSite).toBe('Lax')
 expect(await page.evaluate(()=>document.cookie)).not.toContain('taskflow_session')
 await page.getByRole('link',{name:'个人设置'}).click()
 await page.getByLabel('昵称',{exact:true}).fill('一起交付')
 await page.getByRole('button',{name:'保存资料'}).click()
 await expect(page.getByRole('alert')).toContainText('个人资料已保存')
 await page.reload();await expect(page.getByLabel('昵称',{exact:true})).toHaveValue('一起交付')
 await page.screenshot({path:testInfo.outputPath('settings.png'),fullPage:true})
 const second=await browser.newContext({baseURL})
 try{
  const response=await second.request.post('/api/v1/auth/login',{data:{email,password}});expect(response.status()).toBe(200)
  const otherPage=await second.newPage();await otherPage.goto('/settings');await expect(otherPage.getByLabel('昵称',{exact:true})).toHaveValue('一起交付')
  await page.getByLabel('原密码',{exact:true}).fill('Incorrect-password')
  await page.getByLabel('新密码',{exact:true}).fill(nextPassword)
  await page.getByLabel('确认新密码',{exact:true}).fill(nextPassword)
  await page.getByRole('button',{name:'更新密码'}).click();await expect(page.getByRole('alert')).toContainText('原密码不正确')
  await page.getByLabel('原密码',{exact:true}).fill(password)
  await page.getByRole('button',{name:'更新密码'}).click();await expect(page).toHaveURL(/reason=password_updated/)
  expect((await second.request.get('/api/v1/me')).status()).toBe(401)
  await otherPage.reload();await expect(otherPage).toHaveURL(/\/login/)
 }finally{await second.close()}
 await page.getByLabel('邮箱',{exact:true}).fill(email);await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page.getByText(/邮箱或密码错误/)).toBeVisible()
 await page.getByLabel('密码',{exact:true}).fill(nextPassword);await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page).toHaveURL(/\/teams$/)
 await page.getByRole('button',{name:'退出登录'}).click();await expect(page).toHaveURL(/\/login$/)
 expect((await context.request.get('/api/v1/me')).status()).toBe(401)
 expect(errors).toEqual([])
})

