CREATE TABLE IF NOT EXISTS tasks (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 project_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL,
 description VARCHAR(2000) NOT NULL DEFAULT '',
 status VARCHAR(16) NOT NULL DEFAULT 'todo',
 priority VARCHAR(16) NOT NULL DEFAULT 'medium',
 assignee_id BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 due_at DATE NULL,
 position BIGINT UNSIGNED NOT NULL,
 version BIGINT UNSIGNED NOT NULL DEFAULT 1,
 deleted_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 KEY idx_tasks_board (project_id,status,deleted_at,position,id),
 KEY idx_tasks_assignee (assignee_id,deleted_at,due_at,id),
 KEY idx_tasks_priority (project_id,priority,deleted_at),
 KEY idx_tasks_due (project_id,due_at,deleted_at),
 CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects(id),
 CONSTRAINT fk_tasks_creator FOREIGN KEY (created_by) REFERENCES users(id),
 CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users(id),
 CONSTRAINT chk_tasks_status CHECK (status IN ('todo','in_progress','in_review','done')),
 CONSTRAINT chk_tasks_priority CHECK (priority IN ('low','medium','high','urgent')),
 CONSTRAINT chk_tasks_version CHECK (version > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
